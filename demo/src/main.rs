    /// Whether `[r, g, b]` is one of the tree's greens.
    fn is_tree_green([r, g, b, _]: [u8; 4]) -> bool {
        g > r.saturating_add(40) && g > b.saturating_add(40)
    }

    /// Whether `[r, g, b]` is the placeholder's magenta.
    fn is_placeholder_magenta([r, g, b, _]: [u8; 4]) -> bool {
        r > 200 && b > 200 && g < 60
    }

    fn count_pixels(image: &sfeg::capture::CapturedImage, test: fn([u8; 4]) -> bool) -> usize {
        image
            .rgba8()
            .as_chunks::<4>()
            .0
            .iter()
            .filter(|&&pixel| test(pixel))
            .count()
    }

