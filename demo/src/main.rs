    #[test]
    fn trees_draw_placeholders_until_the_renderer_has_their_texture() {
        let mut core = setup().unwrap();
        let mut renderer =
            OffscreenRenderer::new(NonZeroU32::new(320).unwrap(), NonZeroU32::new(180).unwrap())
                .unwrap();
        // The texture may be ready in the core already, but the renderer
        // hasn't been given it.
        let image = renderer.render_to_image(&core.draw()).unwrap();
        assert!(count_pixels(&image, is_placeholder_magenta) > 50);
        assert_eq!(count_pixels(&image, is_tree_green), 0);
    }

    /// Releases the scene's loads of one texture on its first tick.
    struct ReleaseFromSceneOnFirstTick {
        texture: TextureHandle,
        loads: u32,
    }

    impl GameObject for ReleaseFromSceneOnFirstTick {
        fn tick(&mut self, ctx: &mut TickContext) {
            for _ in 0..std::mem::take(&mut self.loads) {
                ctx.release_texture_from_scene_scope_deferred(self.texture)
                    .unwrap();
            }
        }
    }

    /// Needs a GPU driver.
    #[test]
    fn a_freed_texture_draws_as_the_placeholder() {
        let mut core = setup().unwrap();
        // The meadow's file loaded it once per tree; this third load is for
        // the handle.
        let tree = core.load_texture_into_current_scene_scope(assets::TREE);
        core.current_scene_mut()
            .spawn_immediate(
                ReleaseFromSceneOnFirstTick {
                    texture: tree,
                    loads: 3,
                },
                Parent::Root,
                Transform::IDENTITY,
            )
            .unwrap();
        core.block_until_pending_loads_finish();
        let mut renderer =
            OffscreenRenderer::new(NonZeroU32::new(320).unwrap(), NonZeroU32::new(180).unwrap())
                .unwrap();
        renderer.apply_texture_changes(core.drain_texture_changes_for_renderer());
        let image = renderer.render_to_image(&core.draw()).unwrap();
        assert!(count_pixels(&image, is_tree_green) > 100);

        // Freed when the tick ends. The trees still draw with the old
        // handle, which the renderer no longer has.
        core.tick();
        assert!(matches!(core.texture_state(tree), TextureState::Unloaded));
        renderer.apply_texture_changes(core.drain_texture_changes_for_renderer());
        let image = renderer.render_to_image(&core.draw()).unwrap();
        assert!(count_pixels(&image, is_placeholder_magenta) > 50);
        assert_eq!(count_pixels(&image, is_tree_green), 0);
    }

    fn current_level(core: &Core<HelloGame>) -> Level {
        core.current_scene()
            .scene_state::<LevelState>()
            .expect("the demo's scenes use LevelState")
            .level
    }

    /// Holds `key` and ticks until the current level is `level`, finishing
    /// loads after every tick so the switch doesn't depend on timing.
    /// Returns how many ticks it took, and panics after ten seconds.
    fn walk_until_level(core: &mut Core<HelloGame>, key: KeyCode, level: Level) -> u32 {
        core.apply_input_event(InputEvent::KeyPressed(key));
        let mut tick_count = 0;
        while current_level(core) != level {
            assert!(tick_count < 600, "never reached the {level:?}");
            core.tick();
            core.block_until_pending_loads_finish();
            tick_count += 1;
        }
        core.apply_input_event(InputEvent::KeyReleased(key));
        tick_count
    }

    #[test]
    fn walking_into_the_door_switches_to_the_clearing_and_frees_the_trees() {
        let mut core = setup().unwrap();
        core.block_until_pending_loads_finish();
        let tree = core.load_texture_into_current_scene_scope(assets::TREE);
        assert!(matches!(core.texture_state(tree), TextureState::Ready(_)));

        // 4.4 units at 3 per second is about 88 ticks, then a tick for the
        // door to tell the scene state and one for the switch.
        let tick_count = walk_until_level(&mut core, KeyCode::KeyD, Level::Clearing);
        assert!((85..100).contains(&tick_count), "{tick_count}");

        // The clearing has no trees, so its scene doesn't hold the texture
        // and the meadow's scope ended with the switch.
        assert!(matches!(core.texture_state(tree), TextureState::Unloaded));
        assert_eq!(core.draw().draw_commands().len(), 4);
        assert!(core.next_scene().is_none());
        assert_eq!(core.game_state().scene_changes, 1);
    }

    /// Needs a GPU driver.
    #[test]
    fn walking_back_to_the_meadow_loads_the_trees_again() {
        let mut core = setup().unwrap();
        walk_until_level(&mut core, KeyCode::KeyD, Level::Clearing);
        walk_until_level(&mut core, KeyCode::KeyA, Level::Meadow);
        assert_eq!(core.game_state().scene_changes, 2);

        // The scene state waited for the texture before switching, so the
        // trees draw right away.
        let mut renderer =
            OffscreenRenderer::new(NonZeroU32::new(320).unwrap(), NonZeroU32::new(180).unwrap())
                .unwrap();
        renderer.apply_texture_changes(core.drain_texture_changes_for_renderer());
        let image = renderer.render_to_image(&core.draw()).unwrap();
        assert!(count_pixels(&image, is_tree_green) > 100);
        assert_eq!(count_pixels(&image, is_placeholder_magenta), 0);
    }

    #[test]
    fn walking_past_the_door_does_not_change_scenes() {
        let mut core = setup().unwrap();
        // Along the back edge, outside the doorway.
        core.apply_input_event(InputEvent::KeyPressed(KeyCode::KeyW));
        ticks(&mut core, 120);
        core.apply_input_event(InputEvent::KeyPressed(KeyCode::KeyD));
        ticks(&mut core, 240);
        assert_eq!(current_level(&core), Level::Meadow);
        assert!(core.next_scene().is_none());
    }
