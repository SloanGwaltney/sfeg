/// A texture listed in the game's asset manifest.
///
/// Games get these as constants generated by `sfeg_build`, such as
/// `assets::PLAYER_IDLE`, so a misspelled name is a compile error and the
/// build has already checked that the file exists.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct TextureAsset {
    name: &'static str,
    path: &'static str,
}

impl TextureAsset {
    /// The texture named `name` in the manifest, whose file is at `path`
    /// inside the asset folder, with `/` between folders.
    ///
    /// Generated code calls this. Writing one by hand skips the build's
    /// checks: a wrong path is only found when loading it fails.
    pub const fn from_manifest(name: &'static str, path: &'static str) -> TextureAsset {
        TextureAsset { name, path }
    }

    /// The name the manifest gives it, such as `"player_idle"`.
    pub fn name(&self) -> &'static str {
        self.name
    }

    /// Where its file is, inside the asset folder.
    pub fn path(&self) -> &'static str {
        self.path
    }
}

/// Refers to a loaded texture (ADR 0004, 0015).
///
/// It is `Copy` and holds no data: look the texture up with
/// [`Core::texture_state`](crate::Core::texture_state) or a tick context.
/// Once the texture is freed, the handle reports it as
/// [unloaded](TextureState::Unloaded), even if another texture later
/// reuses its slot.
#[derive(Clone, Copy, PartialEq, Eq, Hash)]
pub struct TextureHandle {
    index: u32,
    generation: u32,
}

impl fmt::Debug for TextureHandle {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "TextureHandle({}v{})", self.index, self.generation)
    }
}

/// Where a texture is in loading. Every state is possible for any handle,
/// so code that uses a texture handles each one.
#[derive(Debug, Clone, Copy)]
pub enum TextureState<'a> {
    /// Its file is being read and decoded on a background thread.
    Loading,
    /// Decoded and ready to draw. The renderer uploads it to the GPU on
    /// its own.
    Ready(&'a DecodedTexture),
    /// Loading failed. It stays failed: loading it again gives the same
    /// handle and the same error.
    Failed(&'a TextureLoadError),
    /// No scope holds it any longer, so it was freed.
    Unloaded,
}

/// A texture's pixels, decoded in the core (ADR 0006).
///
/// Pixels are 8-bit RGBA, sRGB-encoded, from the top row down. Cloning it
/// shares the pixels instead of copying them.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DecodedTexture {
    width_px: NonZeroU32,
    height_px: NonZeroU32,
    rgba8: Arc<[u8]>,
}

impl DecodedTexture {
    /// The width, in pixels.
    pub fn width_px(&self) -> NonZeroU32 {
        self.width_px
    }

    /// The height, in pixels.
    pub fn height_px(&self) -> NonZeroU32 {
        self.height_px
    }

    /// Every pixel, 4 bytes each, from the top row down.
    pub fn rgba8(&self) -> &[u8] {
        &self.rgba8
    }
}

/// Why a texture failed to load.
#[derive(Debug)]
#[non_exhaustive]
pub enum TextureLoadError {
    /// Its file couldn't be read, such as when it was deleted after the
    /// build checked it.
    ReadFile(std::io::Error),
    /// The file isn't a valid PNG, or uses a feature the decoder doesn't
    /// support.
    DecodePng(Box<dyn Error + Send + Sync>),
    /// It is wider or taller than [`MAX_TEXTURE_SIDE_PX`].
    TooLarge {
        /// Its width, in pixels.
        width_px: u32,
        /// Its height, in pixels.
        height_px: u32,
    },
    /// The decoder panicked. This is a bug in the decoder, caught so it
    /// fails only this load.
    DecoderPanicked,
    /// No loader thread could run it, such as when the operating system
    /// refused to start any.
    LoaderUnavailable,
}

impl fmt::Display for TextureLoadError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            TextureLoadError::ReadFile(_) => write!(f, "couldn't read the texture's file"),
            TextureLoadError::DecodePng(_) => write!(f, "the texture's file isn't a valid PNG"),
            TextureLoadError::TooLarge {
                width_px,
                height_px,
            } => write!(
                f,
                "the texture is {width_px}x{height_px} pixels, larger than the \
                 {MAX_TEXTURE_SIDE_PX}x{MAX_TEXTURE_SIDE_PX} limit"
            ),
            TextureLoadError::DecoderPanicked => write!(f, "the PNG decoder panicked"),
            TextureLoadError::LoaderUnavailable => {
                write!(f, "no asset loader thread could run the load")
            }
        }
    }
}

impl Error for TextureLoadError {
    fn source(&self) -> Option<&(dyn Error + 'static)> {
        match self {
            TextureLoadError::ReadFile(source) => Some(source),
            TextureLoadError::DecodePng(source) => Some(source.as_ref()),
            TextureLoadError::TooLarge { .. }
            | TextureLoadError::DecoderPanicked
            | TextureLoadError::LoaderUnavailable => None,
        }
    }
}

/// Why a release couldn't be queued (ADR 0025).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum ReleaseTextureError {
    /// The scope doesn't hold the texture: it never loaded it, its loads
    /// are all released already (counting releases queued this tick), the
    /// texture was freed, or the scope is the next scene's and there is no
    /// next scene.
    NotHeldByScope,
}

impl fmt::Display for ReleaseTextureError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ReleaseTextureError::NotHeldByScope => {
                write!(
                    f,
                    "the scope doesn't hold the texture, so it can't release it"
                )
            }
        }
    }
}

impl Error for ReleaseTextureError {}

/// How the textures a scope holds are doing, such as to show a loading
/// bar for the next scene. Every texture the scope holds is counted once,
/// however many times the scope loaded it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ScopeLoadCounts {
    /// Textures still being read and decoded.
    pub loading: usize,
    /// Textures ready to draw.
    pub ready: usize,
    /// Textures that failed to load.
    pub failed: usize,
}

impl ScopeLoadCounts {
    /// Whether every texture the scope holds has finished loading,
    /// successfully or not. True for a scope that holds nothing.
    pub fn all_finished(&self) -> bool {
        self.loading == 0
    }
}

/// Which scope a load or release is for. Public methods name it instead,
/// such as `load_texture_into_game_scope`, so each context offers only
/// the scopes it may use.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum AssetScope {
    /// Held until the game ends.
    Game,
    /// Held until the scene with this scope ends.
    Scene(SceneScopeId),
}

/// Tells one scene's scope from another's, such as the current scene's
/// from the next scene's while both hold a texture. Never reused.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct SceneScopeId(u64);

/// The engine-owned store of loaded assets (ADR 0004).
pub(crate) struct AssetStore {
    /// What the manifest's paths are relative to.
    asset_folder: PathBuf,
    texture_slots: Vec<TextureSlot>,
    /// Free slot indices, reused last-in, first-out.
    free_texture_slots: Vec<u32>,
    /// The live texture loaded for each manifest name.
    textures_by_name: HashMap<&'static str, TextureHandle>,
    /// Started on the first load, so games without assets start no
    /// threads.
    loader: LoaderStatus,
    /// Textures whose loads are queued or running.
    loads_in_flight: usize,
    /// Loads that finished since the last tick started.
    finished_since_last_tick: Vec<TextureHandle>,
    /// Loads the current tick reports as finished.
    finished_this_tick: Vec<TextureHandle>,
    /// Textures for the renderer to upload or free, oldest first.
    texture_changes_for_renderer: Vec<TextureChange>,
    current_scene_scope: SceneScopeId,
    /// `Some` while the core holds a next scene.
    next_scene_scope: Option<SceneScopeId>,
    /// The ID the next scene scope to begin gets.
    unused_scene_scope_id: u64,
    /// Releases to apply when the tick ends, oldest first.
    queued_releases: Vec<QueuedRelease>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct QueuedRelease {
    texture: TextureHandle,
    scope: AssetScope,
}

enum LoaderStatus {
    NotStarted,
    Running(TextureLoader),
    /// It couldn't start, so every load fails.
    Unavailable,
}

struct TextureSlot {
    generation: u32,
    /// `None` when the slot is free.
    entry: Option<TextureEntry>,
}

struct TextureEntry {
    asset: TextureAsset,
    load: TextureLoad,
    /// Each scope that holds it, once. Never empty: an entry with no holds
    /// is freed.
    holds: Vec<ScopeHold>,
}

struct ScopeHold {
    scope: AssetScope,
    /// Loads not yet released. Never zero: a hold whose loads are all
    /// released is removed.
    loads: u32,
}

enum TextureLoad {
    Loading,
    Ready(DecodedTexture),
    Failed(TextureLoadError),
}

impl AssetStore {
    pub(crate) fn new(asset_folder: PathBuf) -> AssetStore {
        AssetStore {
            asset_folder,
            texture_slots: Vec::new(),
            free_texture_slots: Vec::new(),
            textures_by_name: HashMap::new(),
            loader: LoaderStatus::NotStarted,
            loads_in_flight: 0,
            finished_since_last_tick: Vec::new(),
            finished_this_tick: Vec::new(),
            texture_changes_for_renderer: Vec::new(),
            current_scene_scope: SceneScopeId(0),
            next_scene_scope: None,
            unused_scene_scope_id: 1,
            queued_releases: Vec::new(),
        }
    }

    /// The current scene's scope.
    pub(crate) fn current_scene_scope(&self) -> AssetScope {
        AssetScope::Scene(self.current_scene_scope)
    }

    /// The next scene's scope, if the core holds a next scene.
    pub(crate) fn next_scene_scope(&self) -> Option<AssetScope> {
        self.next_scene_scope.map(AssetScope::Scene)
    }

    /// Starts loading `asset` and adds a load of it to `scope`. If it is
    /// already loaded or loading, only the load is added.
    pub(crate) fn load_texture(&mut self, asset: TextureAsset, scope: AssetScope) -> TextureHandle {
        if let Some(&texture) = self.textures_by_name.get(asset.name) {
            let entry = self
                .texture_entry_mut(texture)
                .expect("a texture stays in the name map only while it is live");
            entry.add_load(scope);
            return texture;
        }

        let texture = self.reserve_texture_slot();
        let mut entry = TextureEntry {
            asset,
            load: TextureLoad::Loading,
            holds: Vec::new(),
        };
        entry.add_load(scope);
        self.texture_slots[texture.index as usize].entry = Some(entry);
        self.textures_by_name.insert(asset.name, texture);

        let job = TextureLoadJob {
            texture,
            path: self.asset_folder.join(asset.path),
        };
        match self.loader() {
            Some(loader) => match loader.queue(job) {
                Ok(()) => self.loads_in_flight += 1,
                Err(_) => {
                    self.loader = LoaderStatus::Unavailable;
                    self.finish_load(texture, Err(TextureLoadError::LoaderUnavailable));
                }
            },
            None => self.finish_load(texture, Err(TextureLoadError::LoaderUnavailable)),
        }
        texture
    }

    pub(crate) fn texture_state(&self, texture: TextureHandle) -> TextureState<'_> {
        match self.texture_entry(texture) {
            None => TextureState::Unloaded,
            Some(entry) => match &entry.load {
                TextureLoad::Loading => TextureState::Loading,
                TextureLoad::Ready(decoded) => TextureState::Ready(decoded),
                TextureLoad::Failed(error) => TextureState::Failed(error),
            },
        }
    }

    /// Called as each tick starts: takes in the loads that have finished,
    /// and makes them this tick's finished loads.
    pub(crate) fn start_tick(&mut self) {
        self.take_finished_loads();
        self.finished_this_tick = std::mem::take(&mut self.finished_since_last_tick);
    }

    /// Loads that finished, successfully or not, before this tick started.
    pub(crate) fn finished_this_tick(&self) -> &[TextureHandle] {
        &self.finished_this_tick
    }

    /// Blocks until every load in flight has finished. The next tick
    /// reports them as finished, as if they had finished on their own.
    pub(crate) fn block_until_pending_loads_finish(&mut self) {
        while self.loads_in_flight > 0 {
            let LoaderStatus::Running(loader) = &self.loader else {
                unreachable!("loads are only in flight while the loader runs")
            };
            match loader.wait_for_result() {
                Ok(result) => self.apply_load_result(result),
                Err(_) => self.fail_loads_in_flight(),
            }
        }
    }

    /// Takes the textures for the renderer to upload or free since the
    /// last call.
    pub(crate) fn drain_texture_changes_for_renderer(&mut self) -> Vec<TextureChange> {
        std::mem::take(&mut self.texture_changes_for_renderer)
    }

    /// Queues one of `scope`'s loads of `texture` to be released when the
    /// tick ends, by [`AssetStore::apply_queued_releases`].
    ///
    /// # Errors
    ///
    /// [`ReleaseTextureError::NotHeldByScope`] if `scope` has no load of
    /// it left to release, counting releases already queued.
    pub(crate) fn queue_release(
        &mut self,
        texture: TextureHandle,
        scope: AssetScope,
    ) -> Result<(), ReleaseTextureError> {
        let loads = self
            .texture_entry(texture)
            .map_or(0, |entry| entry.loads_by(scope));
        let release = QueuedRelease { texture, scope };
        let already_queued = self
            .queued_releases
            .iter()
            .filter(|queued| **queued == release)
            .count();
        if loads as usize <= already_queued {
            return Err(ReleaseTextureError::NotHeldByScope);
        }
        self.queued_releases.push(release);
        Ok(())
    }

    /// Applies the releases queued this tick, freeing each texture that no
    /// scope holds any longer. Called when the tick ends.
    pub(crate) fn apply_queued_releases(&mut self) {
        for release in std::mem::take(&mut self.queued_releases) {
            let Some(entry) = self.texture_entry_mut(release.texture) else {
                continue;
            };
            entry.remove_load(release.scope);
            if entry.holds.is_empty() {
                self.free_texture(release.texture);
            }
        }
    }

    /// Begins the next scene's scope, which loads can name from now on.
    pub(crate) fn begin_next_scene_scope(&mut self) {
        assert!(
            self.next_scene_scope.is_none(),
            "the core begins a next scene only when there is none"
        );
        self.next_scene_scope = Some(SceneScopeId(self.unused_scene_scope_id));
        self.unused_scene_scope_id += 1;
    }

    /// Ends the current scene's scope, freeing what only it held, and makes
    /// the next scene's scope the current one. Called when a switch is
    /// applied.
    pub(crate) fn switch_to_next_scene_scope(&mut self) {
        let next = self
            .next_scene_scope
            .take()
            .expect("the core switches only when there is a next scene");
        let ended = std::mem::replace(&mut self.current_scene_scope, next);
        self.end_scope(AssetScope::Scene(ended));
    }

    /// Ends the next scene's scope, freeing what only it held. Called when
    /// a discard is applied.
    pub(crate) fn end_next_scene_scope(&mut self) {
        let next = self
            .next_scene_scope
            .take()
            .expect("the core discards only when there is a next scene");
        self.end_scope(AssetScope::Scene(next));
    }

    /// How the textures `scope` holds are doing.
    pub(crate) fn scope_load_counts(&self, scope: AssetScope) -> ScopeLoadCounts {
        let mut counts = ScopeLoadCounts {
            loading: 0,
            ready: 0,
            failed: 0,
        };
        for (_, entry) in self.live_textures() {
            if entry.loads_by(scope) == 0 {
                continue;
            }
            match entry.load {
                TextureLoad::Loading => counts.loading += 1,
                TextureLoad::Ready(_) => counts.ready += 1,
                TextureLoad::Failed(_) => counts.failed += 1,
            }
        }
        counts
    }

    /// Removes every load `scope` holds, freeing each texture that no scope
    /// holds any longer.
    fn end_scope(&mut self, scope: AssetScope) {
        for index in 0..self.texture_slots.len() {
            let slot = &mut self.texture_slots[index];
            let Some(entry) = &mut slot.entry else {
                continue;
            };
            entry.holds.retain(|hold| hold.scope != scope);
            if entry.holds.is_empty() {
                let texture = TextureHandle {
                    index: index as u32,
                    generation: slot.generation,
                };
                self.free_texture(texture);
            }
        }
    }

    fn loader(&mut self) -> Option<&TextureLoader> {
        if let LoaderStatus::NotStarted = self.loader {
            self.loader = match TextureLoader::start() {
                Ok(loader) => LoaderStatus::Running(loader),
                Err(error) => {
                    tracing::error!(%error, "no asset loader thread could start, so every load fails");
                    LoaderStatus::Unavailable
                }
            };
        }
        match &self.loader {
            LoaderStatus::Running(loader) => Some(loader),
            LoaderStatus::NotStarted | LoaderStatus::Unavailable => None,
        }
    }

    fn take_finished_loads(&mut self) {
        while self.loads_in_flight > 0 {
            let LoaderStatus::Running(loader) = &self.loader else {
                unreachable!("loads are only in flight while the loader runs")
            };
            match loader.try_take_result() {
                Ok(result) => self.apply_load_result(result),
                Err(TryRecvError::Empty) => return,
                Err(TryRecvError::Disconnected) => self.fail_loads_in_flight(),
            }
        }
    }

    fn apply_load_result(&mut self, result: TextureLoadResult) {
        self.loads_in_flight -= 1;
        self.finish_load(result.texture, result.result);
    }

    /// Every loader thread stopped, so the loads in flight never finish.
    fn fail_loads_in_flight(&mut self) {
        tracing::error!("every asset loader thread stopped, so loads in flight fail");
        self.loader = LoaderStatus::Unavailable;
        self.loads_in_flight = 0;
        let loading: Vec<TextureHandle> = self
            .live_textures()
            .filter(|(_, entry)| matches!(entry.load, TextureLoad::Loading))
            .map(|(texture, _)| texture)
            .collect();
        for texture in loading {
            self.finish_load(texture, Err(TextureLoadError::LoaderUnavailable));
        }
    }

    fn finish_load(
        &mut self,
        texture: TextureHandle,
        result: Result<DecodedTexture, TextureLoadError>,
    ) {
        // The texture may have been freed while it loaded. Its result is
        // dropped, even if the slot holds another texture now.
        let Some(entry) = self.texture_entry_mut(texture) else {
            return;
        };
        let name = entry.asset.name;
        match result {
            Ok(decoded) => {
                entry.load = TextureLoad::Ready(decoded.clone());
                self.texture_changes_for_renderer
                    .push(TextureChange::Ready { texture, decoded });
            }
            Err(error) => {
                tracing::error!(asset = name, error = %ErrorChain(&error), "a texture failed to load");
                entry.load = TextureLoad::Failed(error);
            }
        }
        self.finished_since_last_tick.push(texture);
    }

    fn free_texture(&mut self, texture: TextureHandle) {
        let slot = &mut self.texture_slots[texture.index as usize];
        let Some(entry) = slot.entry.take() else {
            return;
        };
        slot.generation = slot.generation.wrapping_add(1);
        self.free_texture_slots.push(texture.index);
        self.textures_by_name.remove(entry.asset.name);
        if let TextureLoad::Ready(_) = entry.load {
            self.texture_changes_for_renderer
                .push(TextureChange::Freed { texture });
        }
    }

    fn reserve_texture_slot(&mut self) -> TextureHandle {
        if let Some(index) = self.free_texture_slots.pop() {
            let generation = self.texture_slots[index as usize].generation;
            return TextureHandle { index, generation };
        }
        let index = u32::try_from(self.texture_slots.len())
            .expect("a game can't hold more than u32::MAX textures");
        self.texture_slots.push(TextureSlot {
            generation: 0,
            entry: None,
        });
        TextureHandle {
            index,
            generation: 0,
        }
    }

    fn texture_entry(&self, texture: TextureHandle) -> Option<&TextureEntry> {
        let slot = self.texture_slots.get(texture.index as usize)?;
        if slot.generation != texture.generation {
            return None;
        }
        slot.entry.as_ref()
    }

    fn texture_entry_mut(&mut self, texture: TextureHandle) -> Option<&mut TextureEntry> {
        let slot = self.texture_slots.get_mut(texture.index as usize)?;
        if slot.generation != texture.generation {
            return None;
        }
        slot.entry.as_mut()
    }

    fn live_textures(&self) -> impl Iterator<Item = (TextureHandle, &TextureEntry)> {
        self.texture_slots
            .iter()
            .enumerate()
            .filter_map(|(index, slot)| {
                let entry = slot.entry.as_ref()?;
                let texture = TextureHandle {
                    index: index as u32,
                    generation: slot.generation,
                };
                Some((texture, entry))
            })
    }
}

impl TextureEntry {
    fn add_load(&mut self, scope: AssetScope) {
        match self.holds.iter_mut().find(|hold| hold.scope == scope) {
            Some(hold) => {
                hold.loads = hold
                    .loads
                    .checked_add(1)
                    .expect("a scope can't load one texture more than u32::MAX times");
            }
            None => self.holds.push(ScopeHold { scope, loads: 1 }),
        }
    }

    /// Removes one of `scope`'s loads, and its hold once none are left.
    fn remove_load(&mut self, scope: AssetScope) {
        let Some(position) = self.holds.iter().position(|hold| hold.scope == scope) else {
            return;
        };
        self.holds[position].loads -= 1;
        if self.holds[position].loads == 0 {
            self.holds.swap_remove(position);
        }
    }

    /// How many loads by `scope` aren't released yet.
    fn loads_by(&self, scope: AssetScope) -> u32 {
        self.holds
            .iter()
            .find(|hold| hold.scope == scope)
            .map_or(0, |hold| hold.loads)
    }
}

/// Shows an error with all its causes, for logging.
struct ErrorChain<'a>(&'a dyn Error);

impl fmt::Display for ErrorChain<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)?;
        let mut source = self.0.source();
        while let Some(cause) = source {
            write!(f, ": {cause}")?;
            source = cause.source();
        }
        Ok(())
    }
}

